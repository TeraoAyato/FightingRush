Bg::Bg() :
	m_bgHandle(-1)
{
}

Bg::~Bg()
{
}

void Bg::Init()
{
	m_bgHandle = LoadGraph("sozai/Map/tileset.png");
}

void Bg::End()
{
	if (m_bgHandle != -1)
	{
		DeleteGraph(m_bgHandle);
		m_bgHandle = -1;
	}
}

void Bg::Update()
{
}

void Bg::Draw()
{
	if (m_bgHandle == -1) return;

	for (int y = 0; y < kChipNumY; y++)
	{
		for (int x = 0; x < kChipNumX; x++)
		{
			int chipNo = kChipSetting[y][x];

			// -1 は描画スキップ（透明マス扱い）
			if (chipNo < 0) continue;

			// chipNoから画像上のコマ位置（indexX, indexY）を計算
			int indexX = chipNo % kGraphChipNumX;
			int indexY = chipNo / kGraphChipNumX;

			// 切り抜いて画面に描画
			DrawRectGraph(
				kChipSize * x, kChipSize * y,           // 画面上の配置座標
				indexX * kChipSize, indexY * kChipSize, // 画像内の切抜き座標
				kChipSize, kChipSize,                   // 切り抜く幅・高さ (32, 32)
				m_bgHandle, TRUE
			);
		}
	}

#ifdef _DEBUG	// マップチップの境界線
	// 1. 縦線を描く
	for (int x = 0; x <= kChipNumX; x++)
	{
		int lineX = x * kChipSize;
		// (lineX, 0) から (lineX, 画面下端) まで縦線を引く
		DrawLine(lineX, 0, lineX, Game::kScreenHeight, GetColor(230, 230, 230));
	}

	// 2. 横線を描く
	for (int y = 0; y <= kChipNumY; y++)
	{
		int lineY = y * kChipSize;
		// (0, lineY) から (画面右端, lineY) まで横線を引く
		DrawLine(0, lineY, Game::kScreenWidth, lineY, GetColor(230, 230, 230));
	}
#endif
}