void Bg::Init()
{
	// 使用するマップをメモリにロード
	m_BgHandle = LoadGraph("sozai/Map/tileset.png");
}

void Bg::End()
{
	// ロードしたマップをメモリから削除
	DeleteGraph(m_BgHandle);
}

void Bg::Update()
{
}

void Bg::Draw()
{
	for (int y = 0; y < kChipNumY; y++)
	{


		for (int x = 0; x < kChipNumX; x++)
		{
			int chipNo = kChipSetting[y][x];
			// 通し番号で指定されているチップを
			// // 左から何番目、上から何番目、という2つのデータに変換したい

			// chipNoからindexXとindexYを計算で求めたい
			int indexX = chipNo % kGraphChipNumX;
			int indexY = chipNo / kGraphChipNumX;

			DrawRectGraph(kChipSize * x, kChipSize * y, // 画面上の位置
				indexX * kChipSize, indexY * kChipSize, kChipSize, kChipSize, // 切り取り位置の指定
				m_BgHandle, true);
		}
	}
}
